-- SCRIPT DE RECONSTRUCCIÓN DE BASE DE DATOS (OCEAN DRIVE)
-- PLATAFORMA: SUPABASE (POSTGRESQL)

-- 1. Tabla de Usuarios (Equivalente a 'users')
CREATE TABLE IF NOT EXISTS public.users (
    id UUID PRIMARY KEY DEFAULT auth.uid(),
    name TEXT NOT NULL,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    role TEXT DEFAULT 'user' CHECK (role IN ('admin', 'user')),
    nationality TEXT DEFAULT 'Colombia',
    doc_type TEXT DEFAULT 'CC',
    doc_number TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2. Tabla de Categorías (Equivalente a 'categories')
CREATE TABLE IF NOT EXISTS public.categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    base_price DECIMAL(15,2) NOT NULL DEFAULT 0,
    special_periods JSONB DEFAULT '[]'::jsonb,
    luggage INTEGER DEFAULT 2,
    image_url TEXT,
    description TEXT,
    passengers INTEGER DEFAULT 4,
    transmission TEXT DEFAULT 'Automática',
    stock INTEGER DEFAULT 0,
    status TEXT DEFAULT 'active' CHECK (status IN ('active', 'inactive')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 3. Tabla de Vehículos / Instancias (Equivalente a 'vehicles')
CREATE TABLE IF NOT EXISTS public.vehicles (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT REFERENCES public.categories(id) ON DELETE CASCADE,
    plate TEXT UNIQUE NOT NULL,
    wash_price DECIMAL(10,2) DEFAULT 35000,
    status TEXT DEFAULT 'available' CHECK (status IN ('available', 'maintenance', 'offline')),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 4. Tabla de Reservas (Equivalente a 'bookings')
CREATE TABLE IF NOT EXISTS public.bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES public.users(id) ON DELETE SET NULL, -- Opcional si es guest
    category_id BIGINT REFERENCES public.categories(id),
    vehicle_id BIGINT REFERENCES public.vehicles(id),
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    pickup_time TIME DEFAULT '10:00:00',
    dropoff_time TIME DEFAULT '10:00:00',
    pickup_location TEXT DEFAULT 'Cartagena',
    dropoff_location TEXT DEFAULT 'Cartagena',
    total_price DECIMAL(15,2) DEFAULT 0,
    daily_rate DECIMAL(15,2),
    wash_rate DECIMAL(10,2),
    additional_costs JSONB DEFAULT '[]'::jsonb,
    status TEXT DEFAULT 'pending' CHECK (status IN ('pending', 'confirmed', 'cancelled', 'completed', 'maintenance', 'verified', 'offline')),
    code TEXT UNIQUE NOT NULL,
    notes TEXT,
    -- Datos del cliente (snapshot para históricos)
    customer_name TEXT,
    customer_email TEXT,
    customer_phone TEXT,
    customer_phone_code TEXT,
    customer_doc_type TEXT,
    customer_doc_number TEXT,
    customer_nationality TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 5. Tabla de Marketing (Equivalente a 'marketing_subscribers')
CREATE TABLE IF NOT EXISTS public.marketing_subscribers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    email TEXT UNIQUE NOT NULL,
    phone TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 6. Tabla de Solicitudes de Contacto (Equivalente a 'contact_requests')
CREATE TABLE IF NOT EXISTS public.contact_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    phone TEXT,
    email TEXT NOT NULL,
    city TEXT,
    request_date DATE,
    request_time TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

